#[test]
fn recreated_workspace_does_not_inherit_prior_sessions() {
    let root = tempfile::tempdir().unwrap();
    let path = root.path().join("task");
    std::fs::create_dir(&path).unwrap();
    let marker = path.join(".workbranch.task");
    std::fs::write(&marker, "old").unwrap();
    let mut db = store::open_memory().unwrap();
    event::ingest(&mut db,path.to_str().unwrap(),"claude",&json!({"session_id":"s","hook_event_name":"UserPromptSubmit","prompt":"old workspace request"}),100).unwrap();
    // Keep old inode alive to prevent immediate inode reuse in the fixture.
    std::fs::rename(&marker, root.path().join("old-marker")).unwrap();
    std::fs::write(&marker, "new").unwrap();
    assert!(store::snapshot(&db, 100).unwrap().is_empty());
}

