#[test]
fn grok_camel_case_payloads_are_normalized_and_not_recorded_as_claude() {
    let mut db = store::open_memory().unwrap();
    let prompt = json!({"sessionId":"g","hookEventName":"user_prompt_submit","hook_event_name":"UserPromptSubmit","cwd":"/p/t","workspaceRoot":"/p/t","promptId":"turn","prompt":"Fix the UI"});
    assert!(event::ingest(&mut db, "/p/t", "claude", &prompt, 10).is_err());
    event::ingest(&mut db, "/p/t", "grok", &prompt, 10).unwrap();
    event::ingest(&mut db,"/p/t","grok",&json!({"sessionId":"g","hookEventName":"pre_tool_use","promptId":"turn","toolName":"run_terminal_command","toolUseId":"tool","toolInput":{"command":"pnpm test"}}),11).unwrap();
    let state = store::snapshot(&db, 11).unwrap();
    assert_eq!(state.len(), 1);
    assert_eq!(state[0].provider, "grok");
    assert!(state[0].activity.contains("pnpm test"));
    event::ingest(
        &mut db,
        "/p/t",
        "grok",
        &json!({"sessionId":"g","hookEventName":"stop_cancelled","promptId":"turn"}),
        12,
    )
    .unwrap();
    assert_eq!(store::snapshot(&db, 12).unwrap()[0].outcome, "interrupted");
}

#[test]
fn grok_stop_is_tentative_until_idle_and_can_continue_tools() {
    let mut db = store::open_memory().unwrap();
    let send = |db: &mut rusqlite::Connection, event: &str, notification: &str| {
        event::ingest(db,"/p/t","grok",&json!({"sessionId":"g","promptId":"p","hookEventName":event,"notificationType":notification,"toolUseId":"new","toolName":"read_file"}),100).unwrap()
    };
    send(&mut db, "user_prompt_submit", "");
    send(&mut db, "stop", "");
    assert_eq!(
        store::snapshot(&db, 100).unwrap()[0].observation,
        "uncertain"
    );
    send(&mut db, "pre_tool_use", "");
    assert_eq!(store::snapshot(&db, 100).unwrap()[0].state, "running");
    send(&mut db, "stop", "");
    send(&mut db, "notification", "idle_prompt");
    assert_eq!(
        store::snapshot(&db, 100).unwrap()[0].observation,
        "observed"
    );
}

#[test]
fn registered_hook_collector_works_outside_path() {
    let temp = tempfile::tempdir().unwrap();
    let binary = std::path::Path::new(env!("CARGO_BIN_EXE_workbranch-agent-runtime"));
    let result = std::process::Command::new(binary)
        .arg("register")
        .arg(binary)
        .env("WORKBRANCH_RUNTIME_DIR", temp.path())
        .output()
        .unwrap();
    assert!(
        result.status.success(),
        "{}",
        String::from_utf8_lossy(&result.stderr)
    );
    let result = std::process::Command::new(temp.path().join("hook-collector"))
        .arg("version")
        .output()
        .unwrap();
    assert!(result.status.success());
}
