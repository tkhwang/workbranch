#[test]
fn migration_removes_legacy_and_preserves_other_instructions() {
    let root = tempfile::tempdir().unwrap();
    std::fs::write(root.path().join("TASK-WORKBRANCH.md"), "private old plan").unwrap();
    std::fs::write(root.path().join("AGENTS.md"),"<!-- nodeterm:start -->\nkeep me\n<!-- nodeterm:end -->\n# Workbranch Task Guidance\n\nThis file is generated by workbranch for this task workspace.\n\n- Keep the task brief current as work progresses.\n- Before editing a repo, read and follow repo-local agent instructions.\n\n## Custom rules\n- Always test\n").unwrap();
    let paths = vec![root.path().to_path_buf()];
    let preview = migration::run(&paths, false).unwrap();
    assert!(preview.pending > 0);
    assert!(root.path().join("TASK-WORKBRANCH.md").exists());
    migration::run(&paths, true).unwrap();
    assert!(!root.path().join("TASK-WORKBRANCH.md").exists());
    let guidance = std::fs::read_to_string(root.path().join("AGENTS.md")).unwrap();
    assert!(guidance.contains("keep me"));
    assert!(guidance.contains("Always test"));
    assert!(guidance.contains("repo-local"));
    assert!(!guidance.contains("task brief current"));
    assert_eq!(migration::run(&paths, true).unwrap().pending, 0);
}

