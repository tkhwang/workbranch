fn log(states: &[(&str, u64, &str)]) -> Vec<store::Transition> {
    states
        .iter()
        .map(|(state, at, outcome)| store::Transition { state: (*state).into(), at: *at, outcome: (*outcome).into() })
        .collect()
}

