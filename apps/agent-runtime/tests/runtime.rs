#[test]
fn correlated_waits_do_not_resume_on_another_tools_completion() {
    let mut db = store::open_memory().unwrap();
    let send = |db: &mut rusqlite::Connection, hook: &str, id: &str, tool: &str, at| {
        event::ingest(db, "/project/task", "claude", &json!({"session_id":"s", "hook_event_name":hook,"tool_use_id":id,"tool_name":tool,"tool_input":{"command":tool}}), at).unwrap();
    };
    send(&mut db, "PreToolUse", "a", "Bash", 1);
    send(&mut db, "PreToolUse", "b", "AskUserQuestion", 2);
    send(&mut db, "PostToolUse", "a", "Bash", 3);
    assert_eq!(store::snapshot(&db, 3).unwrap()[0].state, "waiting");
    send(&mut db, "PostToolUse", "b", "AskUserQuestion", 4);
    assert_eq!(store::snapshot(&db, 4).unwrap()[0].state, "running");
}

